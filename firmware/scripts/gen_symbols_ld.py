#!/usr/bin/env python3
"""gen_symbols_ld.py — emit a linker symbol file from the provenance manifest.

The "carve-out relink" build compiles a single reconstructed function so it lands at
its original absolute address and calls the rest of the (unchanged) image by name.
This script turns every function in the manifest into a PROVIDE() so reconstructed
C/asm can reference the original image by its Ghidra name (FUN_xxxxxxxx) or, where
known, its real name (main_boot_init, memset, ...).

PROVIDE (not '=') means a symbol the reconstructed unit *defines itself* wins; the
manifest address is only used for symbols the unit references but does not contain.

Usage: gen_symbols_ld.py [manifest.json] [out.ld]
"""
import json, sys, re
from pathlib import Path

REPO = Path("/home/simukka/src/RED/r1mx")
manifest = Path(sys.argv[1]) if len(sys.argv) > 1 else \
    REPO / "firmware/reverse/build_32/src/manifest.json"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else \
    REPO / "firmware/reverse/build_32/src/build/symbols.ld"

recs = json.loads(manifest.read_text())
out.parent.mkdir(parents=True, exist_ok=True)

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
lines = ["/* AUTO-GENERATED by gen_symbols_ld.py — absolute addresses of every",
         " * firmware function, so reconstructed units can call the unchanged image",
         " * by name. PROVIDE: a symbol the unit defines itself overrides this. */"]
seen = set()
n = 0
for r in recs:
    a = r["addr"]
    canon = f"FUN_{a:08x}"          # canonical Ghidra-style handle, always defined
    if canon not in seen:
        lines.append(f"PROVIDE({canon} = 0x{a:08x});")
        seen.add(canon); n += 1
    nm = r["name"]
    if nm and nm != canon and IDENT.match(nm) and nm not in seen:
        lines.append(f"PROVIDE({nm} = 0x{a:08x});")
        seen.add(nm); n += 1

out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} with {n} PROVIDE symbols")
