#!/usr/bin/env python3
"""
ghidra_decompile_addrs.py — decompile SPECIFIC functions on demand.

Ghidra's DB already contains ~12.3k functions but `ghidra_decompile_all.py` only
exported ~10.5k of them, so the functions we need for the boot trace (the init
dispatcher, allocator, usrRoot, module inits …) exist in Ghidra but aren't in
`src/all_functions/`. This pulls them by address without the multi-hour full
re-export, and writes them into `src/all_functions/` so the corpus catches up.

Usage (standalone via pyghidra):
    GHIDRA_INSTALL_DIR=~/Downloads/ghidra_12.0.4_PUBLIC \\
    .venv/bin/python firmware/scripts/ghidra_decompile_addrs.py 0x35a964 0x552bf4 ...
"""
import os, sys

_GHIDRA_HOME = os.environ.get(
    "GHIDRA_INSTALL_DIR", os.path.expanduser("~/Downloads/ghidra_12.0.4_PUBLIC"))
_REPO = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))
_OUTDIR = os.path.join(_REPO, "reverse/build_32/src/all_functions")

import pyghidra
pyghidra.start(install_dir=_GHIDRA_HOME)
from pyghidra import open_project

_ctx = open_project(os.path.join(_REPO, "reverse"), "r1mx")
_project = _ctx.__enter__()
_f = _project.getProjectData().getRootFolder().getFile("software.bin")
currentProgram = _f.getDomainObject("pyghidra_decompile_addrs", False, False, None)

from ghidra.app.decompiler import DecompInterface
from ghidra.util.task import ConsoleTaskMonitor

af = currentProgram.getAddressFactory().getDefaultAddressSpace()
fm = currentProgram.getFunctionManager()
dec = DecompInterface()
dec.openProgram(currentProgram)
mon = ConsoleTaskMonitor()

HDR = ("/* AUTO-GENERATED by ghidra_decompile_addrs.py (on-demand export)\n"
       " * address=0x%08x name=%s size=%d xrefs=%d\n"
       " * Firmware: RED ONE MX build_32/software.bin (PPC405, VxWorks 6.x)\n"
       " * This is Ghidra decompiler pseudocode — not original source.\n */\n\n")

addrs = [int(a, 16) for a in sys.argv[1:] if a.startswith("0x")]
for a in addrs:
    ga = af.getAddress(a)
    fn = fm.getFunctionContaining(ga)
    if fn is None:
        print("0x%08x : NO FUNCTION in Ghidra DB" % a); continue
    ent = fn.getEntryPoint().getOffset()
    res = dec.decompileFunction(fn, 60, mon)
    if not res.decompileCompleted():
        print("0x%08x (%s @0x%08x): decompile FAILED: %s"
              % (a, fn.getName(), ent, res.getErrorMessage())); continue
    nrefs = len(list(fn.getProgram().getReferenceManager()
                     .getReferencesTo(fn.getEntryPoint())))
    code = res.getDecompiledFunction().getC()
    out = os.path.join(_OUTDIR, "0x%08x_%s.c" % (ent, fn.getName()))
    with open(out, "w") as fh:
        fh.write(HDR % (ent, fn.getName(), fn.getBody().getNumAddresses(), nrefs))
        fh.write(code)
    print("0x%08x -> %s @0x%08x  (%d bytes C) -> %s"
          % (a, fn.getName(), ent, len(code), os.path.basename(out)))

print("done.")
