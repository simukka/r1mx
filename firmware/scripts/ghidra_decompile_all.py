"""
ghidra_decompile_all.py -- Decompile every function in the firmware binary.

Iterates all known functions in software.bin, decompiles each one, and writes
a separate .c file to firmware/reverse/build_32/src/all_functions/. Intended
as a one-time bulk export that feeds the semantic search index.

Run ghidra_seed_symbols.py first to improve function name coverage.

Usage (standalone via pyghidra):
    GHIDRA_INSTALL_DIR=~/Downloads/ghidra_12.0.4_PUBLIC \\
    python3 firmware/scripts/ghidra_decompile_all.py

Or as a postScript via analyzeHeadless:
    analyzeHeadless /path/to/r1mx/reverse r1mx \\
        -process software.bin \\
        -postScript ghidra_decompile_all.py \\
        -scriptPath firmware/scripts \\
        -noanalysis

Progress is logged every 100 functions. Expect 10,000–30,000 functions and
2–4 hours of runtime for a full decompile.
"""

import os
import re
import sys

_STANDALONE = "currentProgram" not in dir()

if _STANDALONE:
    import pyghidra

    _GHIDRA_HOME = os.environ.get(
        "GHIDRA_INSTALL_DIR",
        os.path.expanduser("~/Downloads/ghidra_12.0.4_PUBLIC"),
    )
    _REPO = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))
    _PROJ_PATH = os.path.join(_REPO, "reverse")
    _CONSUMER = "pyghidra_decompile_all"

    pyghidra.start(install_dir=_GHIDRA_HOME)

    from pyghidra import open_project

    _project_ctx = open_project(_PROJ_PATH, "r1mx")
    _project = _project_ctx.__enter__()
    _dom_file = _project.getProjectData().getRootFolder().getFile("software.bin")
    if _dom_file is None:
        print("ERROR: software.bin not found in r1mx project")
        _project_ctx.__exit__(None, None, None)
        sys.exit(1)
    currentProgram = _dom_file.getDomainObject(_CONSUMER, True, False, None)
    print("Opened:", currentProgram.getName(), "arch:", currentProgram.getLanguageID())

from ghidra.app.decompiler import DecompInterface
from ghidra.program.flatapi import FlatProgramAPI
from ghidra.util.task import ConsoleTaskMonitor

flat     = FlatProgramAPI(currentProgram)
listing  = currentProgram.getListing()
ref_mgr  = currentProgram.getReferenceManager()
monitor  = ConsoleTaskMonitor()

OUT_DIR = os.path.join(
    os.path.dirname(__file__), "..", "reverse", "build_32", "src", "all_functions"
)
os.makedirs(OUT_DIR, exist_ok=True)

DECOMPILE_TIMEOUT = int(os.environ.get("DECOMPILE_TIMEOUT", "300"))

# Characters not safe for filenames
_UNSAFE = re.compile(r'[^\w\-.]')


def safe_name(s, max_len=80):
    return _UNSAFE.sub('_', s)[:max_len]


def xref_count(fn):
    return sum(1 for _ in ref_mgr.getReferencesTo(fn.getEntryPoint()))


ifc = DecompInterface()
ifc.openProgram(currentProgram)

# Fallback decompiler for functions that exceed the simplification step limit.
# Uses "normalize" style (no iterative simplification) to get basic p-code output.
ifc_fallback = DecompInterface()
ifc_fallback.setSimplificationStyle("normalize")
ifc_fallback.openProgram(currentProgram)

fn_mgr = currentProgram.getFunctionManager()
total_fns = fn_mgr.getFunctionCount()
print(f"\n=== Decompiling all {total_fns} functions → {os.path.abspath(OUT_DIR)} ===\n")

ok_count = 0
skip_count = 0
fail_count = 0
fn_iter = fn_mgr.getFunctions(True)

while fn_iter.hasNext():
    fn = fn_iter.next()

    if fn.isThunk() or fn.isExternal():
        skip_count += 1
        continue

    ep = fn.getEntryPoint().getOffset()
    name = fn.getName()
    fname = f"0x{ep:08x}_{safe_name(name)}.c"
    out_path = os.path.join(OUT_DIR, fname)

    # Skip already-exported files (incremental mode).
    # Delete the file and re-run with DECOMPILE_FORCE=1 to regenerate.
    if os.path.exists(out_path) and not os.environ.get("DECOMPILE_FORCE"):
        ok_count += 1
        continue

    result = ifc.decompileFunction(fn, DECOMPILE_TIMEOUT, monitor)
    if result.decompileCompleted():
        c = result.getDecompiledFunction().getC()
        xrefs = xref_count(fn)
        size = fn.getBody().getNumAddresses()
        header = (
            f"/* AUTO-GENERATED by ghidra_decompile_all.py\n"
            f" * address=0x{ep:08x}  name={name}  size={size}  xrefs={xrefs}\n"
            f" * Firmware: RED ONE MX build_32/software.bin (PowerPC 405F6, VxWorks 6.x)\n"
            f" * This is Ghidra decompiler pseudocode — not original source.\n"
            f" */\n\n"
        )
        with open(out_path, "w") as f:
            f.write(header + c)
        ok_count += 1
    else:
        # Retry with normalized p-code (no iterative simplification) to get
        # basic output from functions that exceed the step limit.
        result2 = ifc_fallback.decompileFunction(fn, DECOMPILE_TIMEOUT, monitor)
        _decomp2 = result2.getDecompiledFunction() if result2.decompileCompleted() else None
        if _decomp2 is not None:
            c = _decomp2.getC()
            xrefs = xref_count(fn)
            size = fn.getBody().getNumAddresses()
            header = (
                f"/* AUTO-GENERATED by ghidra_decompile_all.py [normalize fallback]\n"
                f" * address=0x{ep:08x}  name={name}  size={size}  xrefs={xrefs}\n"
                f" * Firmware: RED ONE MX build_32/software.bin (PowerPC 405F6, VxWorks 6.x)\n"
                f" * This is Ghidra decompiler pseudocode — not original source.\n"
                f" * NOTE: Full decompilation timed out; this is normalized p-code only.\n"
                f" */\n\n"
            )
            with open(out_path, "w") as f:
                f.write(header + c)
            print(f"  ~~ FALLBACK  0x{ep:08x}  {name}  (normalize)")
            ok_count += 1
        else:
            print(f"  !! FAIL  0x{ep:08x}  {name}: {result.getErrorMessage()[:80]}")
            fail_count += 1

    done = ok_count + fail_count
    if done % 100 == 0:
        print(f"  [{done}/{total_fns - skip_count}]  ok={ok_count}  fail={fail_count}  skip={skip_count}")

ifc.dispose()
ifc_fallback.dispose()
print(f"\nDone. ok={ok_count}  fail={fail_count}  skip={skip_count}  → {os.path.abspath(OUT_DIR)}/")

if _STANDALONE:
    currentProgram.release(_CONSUMER)
    _project_ctx.__exit__(None, None, None)
    print("Closed project.")
